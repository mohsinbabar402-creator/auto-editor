def test_05_knowledge_pattern_lifecycle():
    print(f"\n{SEP}\nTEST 5: KnowledgePattern lifecycle (CANDIDATE -> VALIDATED -> ACTIVE -> REJECTED)\n{SEP}")
    repo = KnowledgeRepository(KnowledgeDatabase())

    # Step 1: Record decision so event induction links it
    repo.record_creative_decision(
        project_id="proj_beta", episode_id="ep_01", clip_id="clip_b01",
        decision_type="hook_selection", decision_payload={"hook_type": "shock_statement"},
        reasoning_summary="Bold opening statement.",
    )

    # 1 success -> CANDIDATE
    repo.record_learning_event(
        event_type=LearningEventType.HOOK_PERFORMED_WELL.value,
        source_type="PRODUCTION", source_id="clip_b01", project_id="proj_beta",
    )
    p1 = repo.get_pattern("pat_hook_shock_statement_proj_beta")
    assert p1 is not None
    assert p1.status == PatternStatus.CANDIDATE.value
    assert p1.success_count == 1

    # 3 successes -> VALIDATED
    for i in range(2, 4):
        cid = f"clip_b{i:02d}"
        repo.record_creative_decision("proj_beta", "ep_01", cid, "hook_selection", {"hook_type": "shock_statement"}, "Reason")
        repo.record_learning_event(LearningEventType.HOOK_PERFORMED_WELL.value, "PRODUCTION", cid, "proj_beta")

    p2 = repo.get_pattern("pat_hook_shock_statement_proj_beta")
    assert p2.status == PatternStatus.VALIDATED.value
    assert p2.success_count == 3

    # 5 successes -> ACTIVE
    for i in range(4, 7):
        cid = f"clip_b{i:02d}"
        repo.record_creative_decision("proj_beta", "ep_01", cid, "hook_selection", {"hook_type": "shock_statement"}, "Reason")
        repo.record_learning_event(LearningEventType.HOOK_PERFORMED_WELL.value, "PRODUCTION", cid, "proj_beta")

    p3 = repo.get_pattern("pat_hook_shock_statement_proj_beta")
    assert p3.status == PatternStatus.ACTIVE.value
    assert p3.confidence >= 0.50

    # Series of failures -> REJECTED
    for i in range(7, 15):
        cid = f"clip_b{i:02d}"
        repo.record_creative_decision("proj_beta", "ep_01", cid, "hook_selection", {"hook_type": "shock_statement"}, "Reason")
        repo.record_learning_event(LearningEventType.HOOK_PERFORMED_POORLY.value, "PRODUCTION", cid, "proj_beta")

    p4 = repo.get_pattern("pat_hook_shock_statement_proj_beta")
    assert p4.status == PatternStatus.REJECTED.value
    assert p4.failure_count > p4.success_count

    print(f"  Pattern progressed: CANDIDATE -> VALIDATED -> ACTIVE -> REJECTED (conf: {p4.confidence})")
    print("  PASS: Knowledge pattern lifecycle state machine verified.")


def test_06_mathematical_confidence_calculation():
    print(f"\n{SEP}\nTEST 6: Mathematical Bayesian confidence calculation\n{SEP}")
    # 1 success out of 1 trial should NOT be 1.0 (Laplace + sample dampener prevents 1-hit wonder false activation)
    c_1_of_1 = _calculate_confidence(1, 0)
    assert c_1_of_1 < 0.35, f"1/1 sample should be damped, got {c_1_of_1}"

    # 5 successes out of 5 trials
    c_5_of_5 = _calculate_confidence(5, 0)
    assert 0.45 < c_5_of_5 < 0.80

    # 20 successes out of 22 trials
    c_20_of_22 = _calculate_confidence(20, 2)
    assert c_20_of_22 > 0.65

    # 10 successes out of 20 trials (50% win rate)
    c_10_of_20 = _calculate_confidence(10, 10)
    assert c_10_of_20 < 0.45

    print(f"  Confidence 1/1: {c_1_of_1}, 5/5: {c_5_of_5}, 20/22: {c_20_of_22}, 10/20: {c_10_of_20}")
    print("  PASS: Mathematical confidence calculation avoids false high confidence on small samples.")


