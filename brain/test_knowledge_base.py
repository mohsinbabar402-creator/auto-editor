def test_14_concurrent_thread_safety():
    print(f"\n{SEP}\nTEST 14: Concurrent thread safety & ACID transaction isolation\n{SEP}")
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as td:
        db_path = Path(td) / "concur.db"
        repo = KnowledgeRepository(KnowledgeDatabase(db_path))
        errors = []

        def _worker(thread_idx: int):
            try:
                for i in range(10):
                    cid = f"clip_th_{thread_idx}_{i}"
                    repo.record_creative_decision("proj_concur", "ep_01", cid, "hook", {"idx": i}, "Summary")
                    repo.record_learning_event(LearningEventType.HOOK_PERFORMED_WELL.value, "PRODUCTION", cid, "proj_concur")
            except Exception as e:
                errors.append(e)

        threads = [threading.Thread(target=_worker, args=(t,)) for t in range(5)]
        for t in threads: t.start()
        for t in threads: t.join(timeout=15)

        assert len(errors) == 0, f"Concurrent execution produced errors: {errors}"
        decisions = repo.db.execute("SELECT COUNT(*) as cnt FROM creative_decisions WHERE project_id = 'proj_concur'")
        assert decisions[0]["cnt"] == 50

        repo.db.close()
        print(f"  5 threads concurrently wrote 50 decisions and events with 0 errors.")
        print("  PASS: ACID transaction isolation under concurrent multi-threaded load verified.")


